package com.atividadeAvaliativaLP3.demo.config;

import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.boot.CommandLineRunner;
import org.springframework.core.annotation.Order;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Component;

/**
 * Garante a ESTRUTURA do banco de forma idempotente (DDL seguro, não destrutivo).
 *
 * Por que não usar `spring.jpa.hibernate.ddl-auto=update`?
 * O Hibernate 6 precisa ler muitos metadados do banco (tabelas, colunas, índices) para
 * decidir o que alterar. Através do POOLER do Supabase essas consultas de metadados são
 * interrompidas pelo pooler (`This connection has been closed` / `Socket closed`),
 * o que derrubava a inicialização da aplicação.
 *
 * Com `ddl-auto=none` o Hibernate não lê metadados e este componente aplica as alterações
 * necessárias com comandos idempotentes (`CREATE TABLE IF NOT EXISTS`,
 * `ADD COLUMN IF NOT EXISTS`), que podem ser executados várias vezes sem efeito colateral
 * e SEM apagar dados. O script equivalente também está em `database/estrutura.sql`.
 */
@Component
@Order(900)
public class EstruturaBancoConfig implements CommandLineRunner {

    private static final Logger log = LoggerFactory.getLogger(EstruturaBancoConfig.class);

    private final JdbcTemplate jdbcTemplate;

    public EstruturaBancoConfig(JdbcTemplate jdbcTemplate) {
        this.jdbcTemplate = jdbcTemplate;
    }

    private static final String[] COMANDOS = {
            // Tabela que guarda a resposta de cada aluno por questão (fonte de verdade da pontuação)
            """
            CREATE TABLE IF NOT EXISTS resposta_questao (
                resposta_id integer GENERATED BY DEFAULT AS IDENTITY,
                acertou boolean NOT NULL,
                pontos_aplicados float8 NOT NULL,
                questao_id integer NOT NULL,
                quizz_id integer NOT NULL,
                respondido_em timestamp(6) NOT NULL,
                tempo_segundos integer,
                tentativa_id integer,
                aluno_id integer NOT NULL,
                PRIMARY KEY (resposta_id),
                CONSTRAINT uk_resposta_aluno_questao UNIQUE (aluno_id, questao_id)
            )
            """,
            // Integridade referencial com a tabela de alunos (criada apenas se ainda não existir)
            """
            DO $$
            BEGIN
                IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_resposta_aluno') THEN
                    ALTER TABLE resposta_questao
                        ADD CONSTRAINT fk_resposta_aluno FOREIGN KEY (aluno_id) REFERENCES aluno (usuario_id);
                END IF;
            END $$;
            """,
            // Colunas novas de calibração da dificuldade (não destrutivo)
            "ALTER TABLE questao ADD COLUMN IF NOT EXISTS calibrada boolean",
            "ALTER TABLE questao ADD COLUMN IF NOT EXISTS calibrada_em timestamp(6)",
            "UPDATE questao SET calibrada = false WHERE calibrada IS NULL",
            // Descrição/bio pública do usuário (substitui o antigo professor.biografia)
            "ALTER TABLE usuario ADD COLUMN IF NOT EXISTS descricao text",
            """
            UPDATE usuario
               SET descricao = p.biografia
              FROM professor p
             WHERE p.usuario_id = usuario.id
               AND usuario.descricao IS NULL
               AND p.biografia IS NOT NULL
            """
    };

    @Override
    public void run(String... args) {
        int aplicados = 0;
        for (String sql : COMANDOS) {
            try {
                jdbcTemplate.execute(sql);
                aplicados++;
            } catch (Exception e) {
                Throwable causa = (e instanceof org.springframework.core.NestedRuntimeException nre)
                        ? nre.getMostSpecificCause()
                        : e;
                log.warn("Comando de estrutura do banco ignorado ({}): {}", causa.getMessage(),
                        sql.replaceAll("\\s+", " ").trim().substring(0, Math.min(70, sql.length())));
            }
        }
        log.info("Estrutura do banco verificada: {}/{} comandos idempotentes aplicados com sucesso.",
                aplicados, COMANDOS.length);
    }
}
