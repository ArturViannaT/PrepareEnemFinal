-- 1) Respostas de cada aluno por questão (fonte de verdade da pontuação)
CREATE TABLE IF NOT EXISTS resposta_questao (
    resposta_id integer GENERATED BY DEFAULT AS IDENTITY,
    acertou boolean NOT NULL,
    pontos_aplicados float8 NOT NULL,
    questao_id integer NOT NULL,
    quizz_id integer NOT NULL,
    respondido_em timestamp(6) NOT NULL,
    tempo_segundos integer,
    tentativa_id integer,
    aluno_id integer NOT NULL,
    PRIMARY KEY (resposta_id),
    CONSTRAINT uk_resposta_aluno_questao UNIQUE (aluno_id, questao_id)
);

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_resposta_aluno') THEN
        ALTER TABLE resposta_questao
            ADD CONSTRAINT fk_resposta_aluno FOREIGN KEY (aluno_id) REFERENCES aluno (usuario_id);
    END IF;
END $$;

-- 2) Calibração da dificuldade da questão (modelo adaptativo inspirado na TRI)
ALTER TABLE questao ADD COLUMN IF NOT EXISTS calibrada boolean;
ALTER TABLE questao ADD COLUMN IF NOT EXISTS calibrada_em timestamp(6);
UPDATE questao SET calibrada = false WHERE calibrada IS NULL;

-- 3) Descrição/bio pública do usuário (substitui o antigo professor.biografia)
ALTER TABLE usuario ADD COLUMN IF NOT EXISTS descricao text;

UPDATE usuario
   SET descricao = p.biografia
  FROM professor p
 WHERE p.usuario_id = usuario.id
   AND usuario.descricao IS NULL
   AND p.biografia IS NOT NULL;

-- 4) Views de apoio para gestão (o modelo continua normalizado: nada é duplicado aqui)
CREATE OR REPLACE VIEW vw_usuario_completo AS
SELECT u.id, u.auth_id, u.nome, u.email,
       CASE WHEN p.usuario_id IS NOT NULL THEN 'PROFESSOR' ELSE 'ALUNO' END AS tipo,
       u.foto_perfil, u.descricao, u.created_at
  FROM usuario u
  LEFT JOIN professor p ON p.usuario_id = u.id;

CREATE OR REPLACE VIEW vw_aluno_completo AS
SELECT a.usuario_id, u.nome, u.email, u.auth_id, u.foto_perfil, u.descricao,
       a.pontos, a.nivel, a.xp, a.quizzes_resolvidos,
       (SELECT COUNT(*) FROM resposta_questao r WHERE r.aluno_id = a.usuario_id) AS total_respostas,
       (SELECT COUNT(*) FROM resposta_questao r WHERE r.aluno_id = a.usuario_id AND r.acertou = true) AS total_acertos
  FROM aluno a
  JOIN usuario u ON u.id = a.usuario_id;

CREATE OR REPLACE VIEW vw_professor_completo AS
SELECT p.usuario_id, u.nome, u.email, u.auth_id, u.foto_perfil, p.instituicao, u.descricao,
       (SELECT COUNT(*) FROM conteudo c WHERE c.autor_id = p.usuario_id) AS total_conteudos,
       (SELECT COUNT(*) FROM quizz q WHERE q.autor_id = p.usuario_id) AS total_quizzes
  FROM professor p
  JOIN usuario u ON u.id = p.usuario_id;

CREATE OR REPLACE VIEW vw_questao_desempenho AS
SELECT q.questao_id, q.quizz_id, qz.nome_quizz AS quiz, q.pergunta,
       q.dificuldade_inicial, q.dificuldade_atual,
       CASE q.dificuldade_atual WHEN 'FACIL' THEN 10 WHEN 'DIFICIL' THEN 100 ELSE 50 END AS valor_pontos_atual,
       q.total_respostas, q.total_acertos, q.percentual_acertos, q.calibrada
  FROM questao q
  LEFT JOIN quizz qz ON qz.quizz_id = q.quizz_id;

CREATE OR REPLACE VIEW vw_resposta_detalhada AS
SELECT r.resposta_id, u.nome AS aluno, r.questao_id, r.quizz_id, q.dificuldade_atual,
       r.acertou, r.pontos_aplicados, r.tempo_segundos, r.respondido_em
  FROM resposta_questao r
  JOIN usuario u ON u.id = r.aluno_id
  LEFT JOIN questao q ON q.questao_id = r.questao_id;
